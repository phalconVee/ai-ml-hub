"""Turn the report dict into Markdown (for the download button, or a notes app).

Kept separate from the Streamlit UI so the same Markdown can be produced in a
script or a test, and so the UI file stays about layout only.
"""

from __future__ import annotations

from .pipeline import AnalysisResult

BADGE = {"verified": "✅", "wrong_page": "📄", "not_found": "⚠️"}


def evidence_line(item: dict) -> str:
    """`> "quote" (p. 3) ✅`, plus a note when grounding disagreed."""
    ev, g = item["evidence"], item.get("grounding", {})
    status = g.get("status", "")
    line = f'> "{ev["quote"]}" (p. {ev["page"]}) {BADGE.get(status, "")}'
    if status == "wrong_page":
        line += f" *(actually on p. {g['found_page']})*"
    elif status == "not_found":
        line += " *(quote not found in the PDF; verify by hand)*"
    return line


def to_markdown(result: AnalysisResult) -> str:
    r = result.report
    out = [f"# {r['title']}", "", f"*{r['field']}* · {r['one_line_summary']}", "",
           "## Executive summary", r["executive_summary"], "",
           "## Research question", r["research_question"], "",
           "## Methods",
           f"- **Design:** {r['methods']['study_design']}",
           f"- **Data:** {r['methods']['data']}",
           f"- **Techniques:** {', '.join(r['methods']['techniques'])}",
           f"- **Statistics:** {r['methods']['statistics']}", "",
           "## Key findings"]
    for i, f in enumerate(r["key_findings"], 1):
        figs = f" · figures: {', '.join(f['figure_ids'])}" if f["figure_ids"] else ""
        out += [f"{i}. **{f['claim']}** (confidence: {f['confidence']}{figs})", evidence_line(f), ""]

    out.append("## Figure insights")
    labels = {fig.fig_id: fig.label or "unlabelled" for fig in result.paper.figures}
    for fi in r["figure_insights"]:
        out.append(f"- **{fi['figure_id']}** ({labels.get(fi['figure_id'], '?')}): {fi['insight']}")
    out.append("")

    out.append("## Limitations")
    for lim in r["limitations"]:
        who = "authors" if lim["source"] == "stated_by_authors" else "reviewer"
        out += [f"- **[{who}]** {lim['limitation']}", "  " + evidence_line(lim)]
    out.append("")

    for heading, key in (("Open questions", "open_questions"),
                         ("Practical implications", "practical_implications"),
                         ("Reviewer notes", "reviewer_notes")):
        out.append(f"## {heading}")
        out += [f"- {x}" for x in r[key]] or ["- (none)"]
        out.append("")

    g = result.grounding
    out.append(f"---\nGrounding: {g['verified']} quotes verified, {g['wrong_page']} on another "
               f"page, {g['not_found']} not found. Generated by Paper Lab Analyst.")
    return "\n".join(out)
